// --- lookups ---------------------------------------------------------------

export function getViber(handle: string): Viber | undefined {
  return VIBERS.find((v) => v.handle === handle);
}

export function getRun(code: string): Run | undefined {
  return RUNS.find((r) => r.code.toLowerCase() === code.toLowerCase());
}

export function liveRuns(): Run[] {
  return RUNS.filter((r) => r.status === "live");
}

export function runsFor(handle: string): Run[] {
  return RUNS.filter((r) => r.handle === handle);
}

export function liveRunFor(handle: string): Run | undefined {
  return RUNS.find((r) => r.handle === handle && r.status === "live");
}

export function clipsFor(handle: string): Clip[] {
  return CLIPS.filter((c) => c.handle === handle);
}
